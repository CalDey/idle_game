"""Bot-authored: breathing guard field = smoothstep(distance to protected hair / 36px), sampled every
4px over the protect-layer area (380..745 x 280..565). Written as js/breath_guard.js (base64 uint8)
so the runtime never needs getImageData (file:// safe). Displacement fades to ~0 before static hair,
so the chest-top/strap junction can't tear."""
import numpy as np, cv2, base64
from PIL import Image
R='/workspace/lanyi-portrait-v2-bot/'
a=np.asarray(Image.open(R+'assets/layer_static_protect.png'))[...,3]
free=(a<128).astype(np.uint8)
d=cv2.distanceTransform(free,cv2.DIST_L2,5)
u=np.clip(d/36.0,0,1); g=u*u*(3-2*u)
STEP=4; h,w=g.shape
gs=g[::STEP,::STEP]; gh,gw=gs.shape
q=(gs*255).round().astype(np.uint8)
open(R+'js/breath_guard.js','w').write(
 "/* generated by tools/build_breath_guard.py: guard field for breathing, origin (380,280), step 4px */\n"
 "(function(root){var G={x0:380,y0:280,step:%d,w:%d,h:%d,data:'%s'};"
 "if(typeof module!=='undefined'&&module.exports)module.exports=G;else root.LANYI_BREATH_GUARD=G;})"
 "(typeof self!=='undefined'?self:this);\n"%(STEP,gw,gh,base64.b64encode(q.tobytes()).decode()))
print(gw,gh)
