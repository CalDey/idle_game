"""Bot-authored: hair sway field for lanyi's outer long hair (left side).
No underlay painting: the original image itself is warped continuously inside a closed region (zero
displacement on the region boundary), so nothing can be "left behind" (no ghosts) and hair edges are
the original pixels. Static foreground occluder: sword(+hand) pixels redrawn on top from the original.
Outputs: js/hair_field.js (weight field, base64 uint8, 4px grid), assets/layer_sword_occluder.png,
work/hair/overlay_locks.png (debug)."""
import numpy as np, cv2, base64, json
from PIL import Image
R='/workspace/lanyi-portrait-v2-bot/'
src=np.asarray(Image.open(R+'assets/source_original.jpg').convert('RGB')).astype(np.int32)
H,W,_=src.shape
X0,Y0,X1,Y1=40,250,440,1100          # hair field bbox
r,g,b=src[...,0],src[...,1],src[...,2]
sat=b-np.maximum(r,g)
hair=np.clip((sat-10)/15.0,0,1)
# ---- sword (+hand) occluder: generous hull ∩ non-hair, plus gem
hull=np.array([(196,424),(254,424),(266,500),(294,676),(306,700),(412,735),(414,792),(348,802),(342,850),(378,1100),(238,1100),(230,852),(198,804),(138,792),(138,742),(222,704),(206,500)],np.int32)
hm=np.zeros((H,W),np.uint8); cv2.fillPoly(hm,[hull],1)
sword=((hm>0)&(hair<0.45)).astype(np.uint8)
gem=np.zeros((H,W),np.uint8); cv2.ellipse(gem,(291,771),(17,24),0,0,360,1,-1); sword|=gem&hm
sword=cv2.morphologyEx(sword,cv2.MORPH_OPEN,np.ones((2,2),np.uint8))
sword=cv2.morphologyEx(sword,cv2.MORPH_CLOSE,np.ones((3,3),np.uint8))
# keep only components touching the gem/grip core (drop isolated specks inside hull)
n,lab,st,_=cv2.connectedComponentsWithStats(sword,8)
keep=np.zeros_like(sword)
for i in range(1,n):
    if st[i,cv2.CC_STAT_AREA]>=400: keep[lab==i]=1
sword=keep
occ=cv2.dilate(sword,np.ones((3,3),np.uint8))   # occluder covers sword + 1px edge
# ---- body / sleeve / dress pin: polygon of everything right/below of the hair we must not move
body=np.array([(398,250),(440,250),(440,1100),(40,1100),(125,1060),(165,1005),(205,950),(255,905),(330,880),(302,700),(300,650),(320,560),(372,450),(392,330)],np.int32)
bm=np.zeros((H,W),np.uint8); cv2.fillPoly(bm,[body],1)
# ---- hair mass: hand-traced outer edge (sky/background is as saturated as hair, colour can't separate it)
HAIR_POLY=[(400,280),(340,290),(300,350),(262,400),(236,450),(215,500),(195,550),(165,600),(140,650),(120,700),
           (114,750),(112,800),(118,850),(130,900),(150,950),(172,1000),(250,1000),(330,700),(380,400),(400,280)]
hb=np.zeros((H,W),np.uint8); cv2.fillPoly(hb,[np.array(HAIR_POLY,np.int32)],1)
# outward falloff into background over 40px (region closed: weight 0 at 40px outside hair)
dout=cv2.distanceTransform((1-hb).astype(np.uint8),cv2.DIST_L2,5)
def ss(u): u=np.clip(u,0,1); return u*u*(3-2*u)
w=1-ss(dout/40.0)
# pins
dsw=cv2.distanceTransform((1-occ).astype(np.uint8),cv2.DIST_L2,5)
w*=ss((dsw-3)/28.0)
dbody=cv2.distanceTransform((1-bm).astype(np.uint8),cv2.DIST_L2,5)
w*=ss((dbody-14)/40.0)
w[:Y0+10]=0; w[Y1-10:]=0; w[:,:X0+6]=0; w[:,X1-6:]=0
w=cv2.GaussianBlur(w.astype(np.float32),(0,0),3.0)
w[(occ>0)|(bm>0)]=0
STEP=4
ws=w[Y0:Y1:STEP,X0:X1:STEP]; gh,gw=ws.shape
q=(np.clip(ws,0,1)*255).round().astype(np.uint8)
open(R+'js/hair_field.js','w').write(
 "/* generated by tools/build_hair.py: outer-hair sway weight field, origin (%d,%d), step %dpx */\n"
 "(function(root){var G={x0:%d,y0:%d,step:%d,w:%d,h:%d,data:'%s'};"
 "if(typeof module!=='undefined'&&module.exports)module.exports=G;else root.LANYI_HAIR_FIELD=G;})"
 "(typeof self!=='undefined'?self:this);\n"%(X0,Y0,STEP,X0,Y0,STEP,gw,gh,base64.b64encode(q.tobytes()).decode()))
# occluder layer (crop)
ys,xs=np.where(occ>0); ox0,oy0,ox1,oy1=xs.min(),ys.min(),xs.max()+1,ys.max()+1
a=(occ[oy0:oy1,ox0:ox1]*255).astype(np.uint8)
rgba=np.dstack([src[oy0:oy1,ox0:ox1].astype(np.uint8),a])
Image.fromarray(rgba,'RGBA').save(R+'assets/layer_sword_occluder.png')
json.dump({'occluder_origin':[int(ox0),int(oy0)],'field':[X0,Y0,STEP,gw,gh]},open(R+'work/hair/hair_meta.json','w'))
np.save(R+'work/hair/weight_full.npy',w); np.save(R+'work/hair/occ.npy',occ)
# debug overlay
vis=src.astype(float).copy()
vis[...,1]=vis[...,1]*(1-0.0)+0
heat=np.clip(w,0,1)
vis=vis*(1-0.55*heat[...,None])+np.array([0,255,120])*0.55*heat[...,None]
vis[occ>0]=vis[occ>0]*0.5+np.array([255,60,60])*0.5
edge=cv2.morphologyEx(bm,cv2.MORPH_GRADIENT,np.ones((3,3),np.uint8))>0; vis[edge]=[255,220,0]
out=Image.fromarray(vis[200:1150,0:480].clip(0,255).astype(np.uint8))
out.save(R+'work/hair/overlay_locks.png')
print('occluder origin',ox0,oy0,'size',ox1-ox0,oy1-oy0,'field',gw,gh,'w>0.5 px',int((w>0.5).sum()))
